export function getBossLines(name: string): BossLines {
  return (
    BOSS_LINES[name] ?? {
      intro: '来吧。',
      onRight: ['……'],
      onWrong: ['哼。'],
      onWin: '你赢了。',
      onLose: '你输了。',
    }
  )
}
