/* =============================================================================
   bossLines.ts —— BOSS 的台词
   ---------------------------------------------------------------------------
   为什么非要给 BOSS 写台词：
     一个一动不动的方块怪，用户打两轮就不看它了。
     让它"看着你打、还要点评"—— 战斗的紧张感一半来自这里。
   ========================================================================== */

export interface BossLines {
  /** 开场 */
  intro: string
  /** 宠物答对了（BOSS 心里不爽） */
  onRight: string[]
  /** 宠物答错了（BOSS 得意） */
  onWrong: string[]
  /** 它赢了 */
  onWin: string
  /** 它输了 */
  onLose: string
}

